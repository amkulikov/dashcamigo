for (const loc of LOCALES) {
    const outPath = resolve(ROOT, loc.out);
    console.log(`rendering ${loc.lang} -> ${outPath}`);
    renderHtmlToPng({
        chrome: CHROME,
        html: coverHtml(loc),
        width: 1200,
        height: 630,
        outPath,
        tmpName: `dashcamigo-og-cover-${loc.lang}.html`,
    });
}
console.log("done");
